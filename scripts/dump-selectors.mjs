/**
 * Write docs/UI-SELECTORS.md: every element id in the site, by file.
 *
 * Three separate sessions have now lost time to a test script guessing an id.
 * `#nameInput` and `#phoneInput` did not exist (the real ones are `#custName`
 * and `#custPhone`) and every demand-signal alert would have arrived anonymous
 * because of it. `#doughPhone` did not exist either; it is `#doughCheckPhone`.
 *
 * A hand-written list would rot the first time someone renamed an id, so this
 * is generated. Run it after any UI change:  npm run selectors
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';

const ROOTS = ['src/pages', 'src/components', 'src/layouts'];
const ID = /\bid=["']([A-Za-z][\w-]*)["']/g;

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else if (/\.(astro|html)$/.test(entry)) out.push(full);
  }
  return out;
}

const byFile = new Map();
const seen = new Map(); // id -> [files], so collisions are visible

for (const root of ROOTS) {
  let files = [];
  try { files = walk(root); } catch { continue; }
  for (const file of files) {
    const ids = [...readFileSync(file, 'utf8').matchAll(ID)].map((m) => m[1]);
    const unique = [...new Set(ids)].sort();
    if (!unique.length) continue;
    byFile.set(relative('.', file), unique);
    for (const id of unique) seen.set(id, [...(seen.get(id) ?? []), relative('.', file)]);
  }
}

const dupes = [...seen.entries()].filter(([, files]) => files.length > 1);

let md = `# UI selectors

Generated by \`npm run selectors\` — do not edit by hand.

Every element id in the site, so a test, a script or a console one-liner never
has to guess one. Regenerate after renaming any id.

Total: ${seen.size} ids across ${byFile.size} files.
`;

if (dupes.length) {
  md += `\n## Ids used in more than one file\n\nNot necessarily wrong — a shared component can legitimately appear twice — but\ntwo different elements sharing an id on one rendered page is a bug.\n\n`;
  for (const [id, files] of dupes.sort()) md += `- \`#${id}\` — ${files.join(', ')}\n`;
}

for (const [file, ids] of [...byFile.entries()].sort()) {
  md += `\n## ${file}\n\n`;
  for (const id of ids) md += `- \`#${id}\`\n`;
}

mkdirSync('docs', { recursive: true });
writeFileSync('docs/UI-SELECTORS.md', md);
console.log(`docs/UI-SELECTORS.md: ${seen.size} ids, ${byFile.size} files, ${dupes.length} shared`);
